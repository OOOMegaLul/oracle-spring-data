package dev.plsql.spring.annotation;

import java.lang.annotation.Documented;
import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * Явно задаёт имя подпрограммы PL/SQL (процедуры или функции), которую вызывает метод, и
 * настройки этого вызова.
 *
 * <p>Без аннотации имя выводится из имени метода: {@code setParam} превращается в
 * {@code SET_PARAM}. Подпрограмма ищется в пакете и схеме, заданных в {@link PlsqlApi} на
 * интерфейсе.
 */
@Documented
@Retention(RetentionPolicy.RUNTIME)
@Target(ElementType.METHOD)
public @interface Procedure {

    /**
     * Возвращает имя подпрограммы, например {@code P_FOLDER_DELETE}.
     *
     * <p>Указывается только имя, без пакета и схемы; регистр не важен, имя приводится к
     * верхнему регистру. Пустая строка (значение по умолчанию) означает, что имя выводится из
     * имени метода.
     *
     * @return имя подпрограммы или пустая строка
     */
    String value() default "";

    /**
     * Указывает, передавать ли NULL в обязательные IN-аргументы, для которых метод не дал значения.
     *
     * <p>Многие старые процедуры объявляют длинные списки аргументов без DEFAULT, и вызывающий
     * код передаёт NULL в большую часть из них; этот флаг говорит об этом один раз, а не для
     * каждого аргумента. Касается только аргументов, которые не пришли ни из параметров метода,
     * ни из бина {@code ArgumentDefaults} и у которых нет DEFAULT в PL/SQL (аргументы с DEFAULT
     * просто не передаются, и срабатывает значение по умолчанию из PL/SQL).
     *
     * <p>По умолчанию выключено: забытый аргумент должен останавливать старт приложения, а не
     * молча превращаться в NULL.
     *
     * @return {@code true}, если недостающие обязательные аргументы заполняются NULL
     */
    boolean nullForMissing() default false;

    /**
     * Возвращает, сколько секунд вызов может длиться, прежде чем драйвер его прервёт.
     *
     * <p>Значение по умолчанию {@code -1} означает «как у фабрики» (свойство
     * {@code plsql.query-timeout}); {@code 0} — без ограничения, даже если у фабрики оно задано.
     * Если вызов идёт внутри {@code @Transactional(timeout = ...)}, действует меньшее из двух: этот
     * срок или время, которое осталось у транзакции. Прерванный вызов завершается
     * {@code QueryTimeoutException} (ORA-01013), его изменения данных откатываются.
     *
     * @return предельное время вызова в секундах, {@code 0} или {@code -1}
     */
    int timeout() default -1;

    /**
     * Указывает, что метод вызывает процедуру пакетом: по разу на каждый элемент списка, но за одно
     * обращение к базе на {@link #batchSize()} элементов.
     *
     * <p>Источник элементов — единственный параметр-коллекция или массив метода; каждый элемент —
     * record или бин, чьи свойства сопоставляются с аргументами процедуры (как у объекта-параметра),
     * либо простое значение для аргумента, названного через {@code @Arg} на этом параметре.
     * Остальные параметры метода одинаковы для всех вызовов. Метод возвращает {@code void} или
     * число выполненных вызовов ({@code int}, {@code long}).
     *
     * <p>Только для процедур: выходные значения пакетом не прочитать, поэтому {@code OUT}-аргументы
     * уходят во внутренние переменные блока и отбрасываются; {@code IN OUT}, курсоры и index-by
     * таблицы при старте отвергаются. Вне транзакции Spring весь пакет — одна единица работы:
     * ошибка на любом элементе откатывает все (если соединения пула без {@code autoCommit}).
     * Повтора после ORA-04068 у пакета нет.
     *
     * @return {@code true}, если вызов пакетный
     */
    boolean batch() default false;

    /**
     * Возвращает, сколько вызовов пакета отправлять базе за одно обращение; по умолчанию 1000.
     * Действует только вместе с {@link #batch()}.
     *
     * @return размер пачки, не меньше 1
     */
    int batchSize() default 1000;
}
